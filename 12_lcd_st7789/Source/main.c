/* 显示8x16字符 */
void LCD_ShowAsc8x16(u16 x, u16 y, const unsigned char *asc, u16 color, u16 bcolor)
{
    u16 i, j;
    u8 tmp;
    for(i = 0; i < 16; i++)
    {
        tmp = asc[i];
        for(j = 0; j < 8; j++)
        {
            if(tmp & (0x80 >> j))
                LCD.DrawPoint(x + j, y + i, color);
            else
                LCD.DrawPoint(x + j, y + i, bcolor);
        }
    }
}

/* 显示16x16汉字 */
void LCD_ShowHz16(u16 x, u16 y, const unsigned char *hz, u16 color, u16 bcolor)
{
    u16 i, j;
    u8 tmp;
    for(i = 0; i < 16; i++)
    {
        tmp = hz[i * 2];
        for(j = 0; j < 8; j++)
        {
            if(tmp & (0x80 >> j))
                LCD.DrawPoint(x + j, y + i, color);
            else
                LCD.DrawPoint(x + j, y + i, bcolor);
        }
        tmp = hz[i * 2 + 1];
        for(j = 0; j < 8; j++)
        {
            if(tmp & (0x80 >> j))
                LCD.DrawPoint(x + 8 + j, y + i, color);
            else
                LCD.DrawPoint(x + 8 + j, y + i, bcolor);
        }
    }
}

