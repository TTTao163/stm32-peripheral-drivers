int main(void)
{
    unsigned char text_index = 0;
    unsigned char led_state = 0;
    unsigned int led_count = 0;
    unsigned int text_count = 0;
    
    /* 初始化延时 */
    delay_init(168);
    
    /* 初始化LED */
    led_init();
    turn_off(D1 | D2 | D3 | D4);
    
    /* 初始化LCD并显示实验信息 */
    lcd_init(LCD1);
    
    /* 等待3秒 */
    delay_ms(3000);
    
    /* 清屏 */
    LCD_Clear(0xFFFF);
    
    while(1)
    {
        /* LED D3和D4以0.5Hz频率闪烁 (周期2秒) */
        if(led_count >= 100)
        {
            led_count = 0;
            if(led_state == 0)
            {
                turn_on(D3 | D4);
                led_state = 1;
            }
            else
            {
                turn_off(D3 | D4);
                led_state = 0;
            }
        }
        
        /* 文字轮循显示，间隔2秒 */
        if(text_count >= 200)
        {
            text_count = 0;
            
            /* 清除显示区域 */
            LCD_FillColor(0, 100, 319, 140, 0xFFFF);
            
            /* 根据索引显示不同内容 */
            switch(text_index)
            {
                case 0:
                    LCDDrawFont24(60, 108, "Hello NanGong!", 0x0000, 0xFFFF);
                    break;
                case 1:
                    LCD_ShowIoTPlatform(96, 112, 0x0000, 0xFFFF);  /* 物联网开放平台！ */
                    break;
                case 2:
                    LCD_ShowHz16(140, 112, hz_zhang, 0x0000, 0xFFFF);  /* 张 */
                    LCD_ShowHz16(156, 112, hz_tao, 0x0000, 0xFFFF);    /* 涛 */
                    break;
            }
            
            text_index++;
            if(text_index >= 3)
            {
                text_index = 0;
            }
        }
        
        delay_ms(10);
        led_count++;
        text_count++;
    }
}
